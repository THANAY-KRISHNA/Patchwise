"""Base Language Analyzer Plugin Interface.

All language-specific static checkers and rules must implement this abstract class.
Adding support for new languages (Python, Java, TypeScript, C++, SQL, Scala, etc.)
only requires implementing a new plugin without modifying the core pipeline orchestration.
"""
from abc import ABC, abstractmethod
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel
from ..schemas.findings import FindingCategory, FindingProvenance, FindingSeverity


class LanguageReadiness(str, Enum):
    """Truth-in-advertising language readiness indicator."""
    IMPLEMENTED_AND_TESTED = "IMPLEMENTED_AND_TESTED"
    PLANNED_FRAMEWORK_READY = "PLANNED_FRAMEWORK_READY"


class DiffHunk(BaseModel):
    """Represents a single changed hunk within a unified diff."""
    old_start: int
    old_length: int
    new_start: int
    new_length: int
    header: str
    lines: List[str]
    added_lines: List[int]
    removed_lines: List[int]


class CandidateFinding(BaseModel):
    """Raw finding candidate generated by an analyzer before line grounding validation."""
    rule_id: str
    source: FindingProvenance
    severity: FindingSeverity
    category: FindingCategory
    file_path: str
    start_line: Optional[int] = None
    end_line: Optional[int] = None
    title: str
    explanation: str
    suggested_fix: Optional[str] = None


class TestRecommendation(BaseModel):
    """Targeted test suggestion derived from modified logic."""
    __test__ = False
    target_function: Optional[str] = None
    test_type: str = "unit"
    rationale: str
    sample_test_code: Optional[str] = None


class BaseLanguageAnalyzer(ABC):
    """Abstract base class that all language analysis plugins must implement."""

    @property
    @abstractmethod
    def language_id(self) -> str:
        """Unique lowercase identifier, e.g. 'python', 'typescript', 'java'."""
        pass

    @property
    @abstractmethod
    def name(self) -> str:
        """Human-readable name, e.g. 'Python', 'TypeScript', 'Java'."""
        pass

    @property
    @abstractmethod
    def supported_extensions(self) -> List[str]:
        """List of file extensions, e.g. ['.py'], ['.ts', '.tsx', '.js', '.jsx']."""
        pass

    @property
    @abstractmethod
    def readiness_status(self) -> LanguageReadiness:
        """Declared readiness: IMPLEMENTED_AND_TESTED or PLANNED_FRAMEWORK_READY."""
        pass

    @abstractmethod
    def run_deterministic_checks(
        self, file_path: str, diff_hunks: List[DiffHunk]
    ) -> List[CandidateFinding]:
        """
        Execute deterministic AST or static rules on changed hunks.
        Returns Tier 1 (DETERMINISTIC_STATIC_ANALYSIS) candidate findings.
        """
        pass

    @abstractmethod
    def get_language_prompt_context(self) -> str:
        """
        Provide language-specific guidelines, security anti-patterns,
        and idiomatic rules for optional LLM candidate generation.
        """
        pass

    @abstractmethod
    def suggest_tests(
        self, file_path: str, diff_hunks: List[DiffHunk]
    ) -> List[TestRecommendation]:
        """
        Produce test addition or coverage recommendations for modified constructs.
        """
        pass
