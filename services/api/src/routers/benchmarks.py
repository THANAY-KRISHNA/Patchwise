"""Benchmark Evaluation Results Router for Patchwise."""
import json
import os
from fastapi import APIRouter

router = APIRouter(prefix="/benchmarks", tags=["Evaluation Benchmark"])


@router.get("/latest")
async def get_latest_benchmark_summary(dataset: str = "python"):
    """
    Returns the latest frozen evaluation benchmark results.
    Reads the ground-truth benchmark output generated by benchmark/runner.py.
    """
    d_lower = dataset.lower()
    if d_lower in ("javascript", "js", "ts", "typescript"):
        filename = "results_js_v1.0.0.json"
    elif d_lower in ("java", "jvm"):
        filename = "results_java_v1.0.0.json"
    elif d_lower in ("cpp", "c", "c++"):
        filename = "results_cpp_v1.0.0.json"
    elif d_lower in ("sql", "hql", "hive", "hiveql"):
        filename = "results_sql_v1.0.0.json"
    else:
        filename = "results_v1.0.0.json"
    candidates = [
        os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "benchmark", filename)),
        os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "benchmark", filename)),
        os.path.abspath(os.path.join(os.getcwd(), "benchmark", filename)),
    ]
    for path in candidates:
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)

    return {
        "status": "unavailable",
        "message": f"Benchmark report {filename} not found.",
        "metrics": None,
    }
